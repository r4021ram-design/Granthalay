const fs = require('fs');
const path = require('path');
const Database = require('better-sqlite3');

const DB_PATH = path.join(__dirname, '../storage/granth.db');
const BOOKS_DIR = path.join(__dirname, '../public/data/books');
const REGISTRY_PATH = path.join(__dirname, '../public/data/books.json');

const db = new Database(DB_PATH);

console.log('=== STARTING MASTER HEALING OF ALL PUJAN BOOKS ===\n');

function updateBookInDbAndFiles(bookId, updaterFn) {
  const jsonPath = path.join(BOOKS_DIR, `${bookId}.json`);
  if (!fs.existsSync(jsonPath)) {
    console.log(`[SKIP] File not found: ${jsonPath}`);
    return;
  }

  const bookData = JSON.parse(fs.readFileSync(jsonPath, 'utf8'));
  updaterFn(bookData);

  // Write JSON
  fs.writeFileSync(jsonPath, JSON.stringify(bookData, null, 2), 'utf8');
  console.log(`[OK] Updated JSON for ${bookId}`);

  // Update SQLite
  const now = new Date().toISOString();
  const upsertPage = db.prepare(`
    INSERT INTO pages (
      id, book_id, page_number, original_image_path, preprocessed_image_path,
      width, height, status, ocr_confidence, unresolved_issue_count,
      ocr_text, verified_text, verified_at, verified_by, created_at, updated_at
    ) VALUES (
      @id, @book_id, @page_number, @original_image_path, @preprocessed_image_path,
      @width, @height, @status, @ocr_confidence, @unresolved_issue_count,
      @ocr_text, @verified_text, @verified_at, @verified_by, @created_at, @updated_at
    )
    ON CONFLICT(id) DO UPDATE SET
      verified_text = excluded.verified_text,
      ocr_text = excluded.ocr_text,
      updated_at = excluded.updated_at
  `);

  for (const page of bookData.pages) {
    upsertPage.run({
      id: `${bookId}-p${page.page_number}`,
      book_id: bookId,
      page_number: page.page_number,
      original_image_path: '',
      preprocessed_image_path: '',
      width: 1200,
      height: 1800,
      status: 'VERIFIED',
      ocr_confidence: 1.0,
      unresolved_issue_count: 0,
      ocr_text: page.verified_text,
      verified_text: page.verified_text,
      verified_at: now,
      verified_by: 'Antigravity Liturgical Proofing Engine',
      created_at: now,
      updated_at: now
    });
  }
  console.log(`[OK] Synchronized ${bookData.pages.length} pages into SQLite for ${bookId}`);
}

