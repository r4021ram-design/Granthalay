function extractStotraContent(id) {
  let idIdx = canonicalCode.indexOf(`id: '${id}'`);
  if (idIdx === -1) {
    idIdx = canonicalCode.indexOf(`id: "${id}"`);
  }
  if (idIdx === -1) {
    console.error(`ERROR: ID ${id} not found in canonicalParayanaStotras!`);
    return '';
  }
  const contentStart = canonicalCode.indexOf('content: `', idIdx) + 10;
  const contentEnd = canonicalCode.indexOf('`,\n  }', contentStart);
  return canonicalCode.slice(contentStart, contentEnd).trim();
}

