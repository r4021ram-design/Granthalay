function main() {
  console.log('Writing updated 12-folio Rudrashtadhyayi to JSON and SQLite...');

  // Update book object
  const fullBookData = {
    ...bookMeta,
    pages: pagesData.map(p => ({
      page_number: p.page_number,
      title: p.title,
      text: p.text
    }))
  };

  fs.writeFileSync(TARGET_BOOK_JSON, JSON.stringify(fullBookData, null, 2), 'utf8');
  console.log(`Updated JSON: ${TARGET_BOOK_JSON}`);

  // Update public/data/books.json
  const booksListPath = path.join(JSON_DIR, '../books.json');
  if (fs.existsSync(booksListPath)) {
    const booksList = JSON.parse(fs.readFileSync(booksListPath, 'utf8'));
    const bIdx = booksList.findIndex(b => b.id === BOOK_ID);
    if (bIdx !== -1) {
      booksList[bIdx] = {
        ...booksList[bIdx],
        ...bookMeta
      };
    } else {
      booksList.push(bookMeta);
    }
    fs.writeFileSync(booksListPath, JSON.stringify(booksList, null, 2), 'utf8');
    console.log(`Updated books.json list`);
  }

  // Update SQLite Database
  if (fs.existsSync(DB_PATH)) {
    const db = new Database(DB_PATH);

    // Upsert books table
    const bookDbRecord = {
      id: bookMeta.id,
      title: bookMeta.title,
      author: bookMeta.author,
      description: bookMeta.description,
      language: bookMeta.language,
      page_count: bookMeta.page_count,
      status: bookMeta.status,
      source_type: bookMeta.source_type,
      original_filename: bookMeta.original_filename,
      original_file_path: bookMeta.original_file_path,
      created_at: bookMeta.created_at,
      updated_at: bookMeta.updated_at
    };

    const bookStmt = db.prepare(`
      INSERT INTO books (
        id, title, author, description, language,
        page_count, status, source_type, original_filename, original_file_path,
        created_at, updated_at
      ) VALUES (
        @id, @title, @author, @description, @language,
        @page_count, @status, @source_type, @original_filename, @original_file_path,
        @created_at, @updated_at
      )
      ON CONFLICT(id) DO UPDATE SET
        title = excluded.title,
        author = excluded.author,
        description = excluded.description,
        page_count = excluded.page_count,
        status = excluded.status,
        updated_at = excluded.updated_at
    `);
    bookStmt.run(bookDbRecord);

    // Clean old pages for this book before inserting all 12 pages
    db.prepare('DELETE FROM pages WHERE book_id = ?').run(BOOK_ID);

    // Upsert pages table
    const pageStmt = db.prepare(`
      INSERT INTO pages (
        id, book_id, page_number, original_image_path, preprocessed_image_path,
        verified_text, ocr_text, status, ocr_confidence, created_at, updated_at
      ) VALUES (
        @id, @book_id, @page_number, @original_image_path, @preprocessed_image_path,
        @verified_text, @ocr_text, 'VERIFIED', 1.0, @created_at, @updated_at
      )
    `);

    const nowIso = new Date().toISOString();
    const updatePagesTx = db.transaction((pages) => {
      for (const p of pages) {
        pageStmt.run({
          id: `${BOOK_ID}-p${p.page_number}`,
          book_id: BOOK_ID,
          page_number: p.page_number,
          original_image_path: `/storage/pages/${BOOK_ID}/page-${p.page_number}.png`,
          preprocessed_image_path: `/storage/preprocessed/${BOOK_ID}/page-${p.page_number}-clean.png`,
          verified_text: p.text,
          ocr_text: p.text,
          created_at: nowIso,
          updated_at: nowIso
        });
      }
    });

    updatePagesTx(pagesData);
    db.close();
    console.log(`Synchronized all 12 pages in SQLite database: ${DB_PATH}`);
  }

  console.log('12-folio Rudrashtadhyayi book generation and database synchronization complete!');
}

main();
