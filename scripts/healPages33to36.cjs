const pagesToUpdate = [
  { pageNum: 33, text: PAGE_33 },
  { pageNum: 34, text: PAGE_34 },
  { pageNum: 35, text: PAGE_35 },
  { pageNum: 36, text: PAGE_36 }
];

console.log('Updating JSON and SQLite DB for Pages 33 to 36...');

const updateStmt = db.prepare(`
  UPDATE pages 
  SET verified_text = ?, 
      updated_at = datetime('now')
  WHERE page_number = ?
`);

for (const { pageNum, text } of pagesToUpdate) {
  // 1. Update JSON
  const pg = book.pages.find(p => p.page_number === pageNum);
  if (pg) {
    pg.verified_text = text;
    pg.raw_text = text;
    pg.updated_at = new Date().toISOString();
  }

  // 2. Update SQLite
  const result = updateStmt.run(text, pageNum);
  console.log(`Page ${pageNum}: SQLite updated (${result.changes} rows affected), JSON updated.`);
}

