// 3. Update SQLite database
const dbPath = path.join(__dirname, '../storage/granth.db');
if (fs.existsSync(dbPath)) {
  const db = new Database(dbPath);
  
  const upsertBook = db.prepare(`
    INSERT INTO books (
      id, title, author, description, language, page_count, status,
      source_type, original_filename, original_file_path, created_at, updated_at
    ) VALUES (
      @id, @title, @author, @description, @language, @page_count, @status,
      @source_type, @original_filename, @original_file_path, @created_at, @updated_at
    )
    ON CONFLICT(id) DO UPDATE SET
      title = excluded.title,
      author = excluded.author,
      description = excluded.description,
      page_count = excluded.page_count,
      status = excluded.status,
      updated_at = excluded.updated_at
  `);

  upsertBook.run({
    id: BOOK_ID,
    title: BOOK_TITLE,
    author: BOOK_AUTHOR,
    description: BOOK_DESC,
    language: 'sa',
    page_count: PAGES.length,
    status: 'FULLY_VERIFIED',
    source_type: 'pdf',
    original_filename: `${BOOK_ID}.pdf`,
    original_file_path: bookJsonPath,
    created_at: new Date().toISOString(),
    updated_at: new Date().toISOString()
  });

  db.prepare(`DELETE FROM pages WHERE book_id = ?`).run(BOOK_ID);

  const insertPage = db.prepare(`
    INSERT INTO pages (
      id, book_id, page_number, original_image_path, preprocessed_image_path,
      width, height, status, ocr_confidence, unresolved_issue_count,
      ocr_text, verified_text, verified_at, verified_by, created_at, updated_at
    ) VALUES (
      @id, @book_id, @page_number, @original_image_path, @preprocessed_image_path,
      @width, @height, @status, @ocr_confidence, @unresolved_issue_count,
      @ocr_text, @verified_text, @verified_at, @verified_by, @created_at, @updated_at
    )
  `);

  const now = new Date().toISOString();
  for (const page of PAGES) {
    insertPage.run({
      id: `${BOOK_ID}-p${page.page_number}`,
      book_id: BOOK_ID,
      page_number: page.page_number,
      original_image_path: '',
      preprocessed_image_path: '',
      width: 1200,
      height: 1800,
      status: 'VERIFIED',
      ocr_confidence: 1.0,
      unresolved_issue_count: 0,
      ocr_text: page.verified_text,
      verified_text: page.verified_text,
      verified_at: now,
      verified_by: 'Antigravity Liturgical Proofing Engine',
      created_at: now,
      updated_at: now
    });
  }

  console.log(`[OK] Successfully synchronized ${PAGES.length} clean pages of Janmashtami Balkrishna Pujan into SQLite database.`);
  db.close();
}
