export function cleanFolioHeadersAndFootnotes(text: string): string {
  if (!text) return '';
  let lines = text.split('\n');

  // Strip leading running headers
  while (lines.length > 0) {
    let first = lines[0].trim();
    if (!first) {
      lines.shift();
      continue;
    }

    // Pattern 1: Left page header variants:
    // e.g. (१८) ९ वृहत्स्तोत्ररत्नाकरे वा गजानन ।
    // e.g. बहतस्तोचरत्नाकरे 1११\ उदरे तु...
    // e.g. वृहतस्तोत्रलनाकरे नम खुसर...
    // e.g. , बृहत्स्तोत्ररल्ाकरं विच्य शास्त्रतो ।
    // e.g. वहतस्तोवरत्नाकरे... वृत्तरत्नाकरे...
    const leftMatch = first.match(/^\s*(?:[^A-Za-z\u0900-\u097F\s]*\s*(?:\([^\)]+\)|[०-९\d\s\(\)रष`'"~=\-]+)\s*)?[`'"~=,\-]*\s*(?:[वब][ृुह][^\s]*\s*स्तो[^\s]*|वृ[त्त]+रत्नाकर[ेः]*|स्तोत्रर[त्लतन][^\s]*)\s*(?:[\[\(1][०-९\d१-९]+[\]\)\\])?\s*([`'"~]*\s*)(.*)$/u);
    if (leftMatch && leftMatch[2] !== undefined) {
      const remainder = (leftMatch[2] || '').trim();
      if (!remainder || remainder.length < 3) {
        lines.shift();
        continue;
      } else {
        lines[0] = remainder;
        first = remainder;
      }
    }

    // Pattern 2: Right page header variants:
    // Matches e.g. -शिवस्तोत्राणि' (७५), शिवसतोनाभि (८१), संगादिस्तोकाथि (२३१), संकीर्णसतोतायि (२८३)
    const rightMatch = first.match(/^\s*(?:[^A-Za-z\u0900-\u097F\s]*\s*)?(?:[^\s\(\)\[]+)?\s*(?:[स्शष][्ततलोकव][^\s\(\)\[]*)\s*[`'"~]*\s*[\(\[1][०-९\d१-९\s]+[\)\]\\]\s*[`'"~]*\s*(.*)$/u);
    if (rightMatch && rightMatch[1] !== undefined) {
      const remainder = (rightMatch[1] || '').trim();
      if (!remainder || remainder.length < 3) {
        lines.shift();
        continue;
      } else {
        lines[0] = remainder;
        first = remainder;
      }
    }

    // Pattern 3: Standalone bracket/page number line
    if (/^\s*[\[\(][०-९\d१-९\s]+[\]\)]\s*(?:॥\s*[०-९\d]+\s*॥)?\s*$/u.test(first)) {
      lines.shift();
      continue;
    }

    break;
  }

  // Strip trailing footnote lines & printer artifacts
  while (lines.length > 0) {
    const last = lines[lines.length - 1].trim();
    if (!last) {
      lines.pop();
      continue;
    }

    if (
      /^[०-९\d१-९]\s+.*(?:सुवचम्|प्रयोगः|इत्यर्थः|क्तः|संस्यं|समाप्ता|आर्षोऽयं)/u.test(last) ||
      /^[#£*~_\s`'"।॥—†‡-]+$/u.test(last) ||
      /^[#£]\s*[\u0900-\u097F\s\d£#~`]+$/u.test(last) ||
      /^[०-९\d१-९]\s+॥\s*.*$/u.test(last) ||
      /^[०-९\d१-९]\s*अत्रादिक/u.test(last) ||
      /^\s*`\s*["'~`\s\^vवप~]+$/u.test(last)
    ) {
      lines.pop();
      continue;
    }

    break;
  }

  return lines.join('\n').trim();
}

async function run() {
  console.log('=== Cleaning and Proofing All Brihat Stotra Ratnakar Folios ===');

  interface PageRecord {
    id: string;
    page_number: number;
    verified_text?: string;
    ocr_text?: string;
  }

  const pages = db.prepare("SELECT * FROM pages WHERE book_id = 'granth-brihat-stotra-ratnakar' ORDER BY page_number ASC").all() as PageRecord[];
  console.log(`Found ${pages.length} pages in DB.`);

  const updateStmt = db.prepare("UPDATE pages SET verified_text = ?, updated_at = CURRENT_TIMESTAMP WHERE id = ?");

  let canonicalCount = 0;
  let cleanedCount = 0;

  for (const page of pages) {
    const pNum = page.page_number;
    let newText = '';

    if (canonicalMap[pNum]) {
      newText = canonicalMap[pNum];
      canonicalCount++;
    } else {
      const current = page.verified_text || page.ocr_text || '';
      newText = cleanFolioHeadersAndFootnotes(current);
      cleanedCount++;
    }

    updateStmt.run(newText, page.id);
  }

  console.log(`Updated ${canonicalCount} canonical pages (1-10) and cleaned headers across ${cleanedCount} remaining pages.`);

  // Synchronize JSON
  const updatedPages = db.prepare("SELECT * FROM pages WHERE book_id = 'granth-brihat-stotra-ratnakar' ORDER BY page_number ASC").all();
  const book = db.prepare("SELECT * FROM books WHERE id = 'granth-brihat-stotra-ratnakar'").get();
  const bookJsonPath = path.resolve(ROOT_DIR, 'public/data/books/granth-brihat-stotra-ratnakar.json');
  fs.writeFileSync(bookJsonPath, JSON.stringify({ book, pages: updatedPages }, null, 2));
  console.log('Synchronized public/data/books/granth-brihat-stotra-ratnakar.json!');
}

run().catch(console.error);
