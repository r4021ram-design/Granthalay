/**
 * Helper query functions for Living Puja Paddhati Engine
 */
export function getMantrasByDeity(deityId: LiturgicalMantra['deityId']): LiturgicalMantra[] {
  return SARVA_DEVA_MANTRAS.filter((m) => m.deityId === deityId || m.deityId === 'universal');
}

export function getMantrasBySection(sectionId: LiturgicalMantra['sectionId']): LiturgicalMantra[] {
  return SARVA_DEVA_MANTRAS.filter((m) => m.sectionId === sectionId);
}

export function getMantraById(id: string): LiturgicalMantra | undefined {
  return SARVA_DEVA_MANTRAS.find((m) => m.id === id);
}
