/**
 * Generate Padachheda for a given Sanskrit shloka or mantra text
 */
export function generatePadachheda(text: string): PadachhedaResult {
  if (!text) return { original: '', padachheda: '', splitCount: 0 };

  let splitCount = 0;
  let result = text;

  for (const [pattern, replacement] of PANINIAN_SANDHI_MAP) {
    if (pattern.test(result)) {
      result = result.replace(pattern, replacement);
      splitCount++;
    }
  }

  return {
    original: text,
    padachheda: result,
    splitCount,
  };
}
